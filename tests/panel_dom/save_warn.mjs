import fs from "fs";
import { JSDOM } from "jsdom";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const PAYLOAD = process.argv[2] || path.join(HERE, "payload.json");
const PANEL = pathToFileURL(path.join(HERE, "..", "..", "custom_components", "homepower", "frontend", "homepower-panel.js")).href;
const payload = JSON.parse(fs.readFileSync(PAYLOAD, "utf8"));
const w = new JSDOM("<body></body>", { url: "http://localhost/" }).window;
for (const k of ["HTMLElement", "customElements", "document", "MouseEvent", "Event"]) globalThis[k] = w[k];
Object.defineProperty(globalThis, "localStorage", { value: w.localStorage, configurable: true });
Object.defineProperty(globalThis, "navigator", { value: {}, configurable: true });
const alerts = [], calls = [];
globalThis.alert = (m) => alerts.push(m); globalThis.confirm = () => true;
process.on("unhandledRejection", (e) => { console.log("UNHANDLED", e && e.stack); process.exitCode = 1; });
await import(`${PANEL}?v=1`);
const el = document.createElement("homepower-panel"); document.body.appendChild(el);
el.hass = { states: {}, callWS: async (m) => { calls.push(m); if (m.type === "homepower/get") return payload.get;
  if (m.type === "homepower/schedule/save") return { ...m.schedule, warnings: ["The target (5%) is not above A's minimum charge (10%)."] };
  if (m.type === "homepower/goal/save") return { ...m.goal, warnings: [] }; return {}; },
  connection: { subscribeMessage: () => Promise.resolve(() => {}) } };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await wait(200);
el.tab = "schedules"; el._render();
const root = el.shadowRoot;
root.querySelector('[data-act="add-schedule"]').dispatchEvent(new w.MouseEvent("click", { bubbles: true, composed: true }));
await wait(50);
const modal = root.getElementById("modal");
const ids = [...modal.querySelectorAll("[id]")].map((e) => e.id).filter((i) => i.startsWith("sc-") || i.startsWith("s-") || i.startsWith("sch"));
console.log("modal ids:", ids.slice(0, 12).join(","));
const idEl = root.getElementById('s-name');
idEl.value = "My night";
root.querySelector('[data-act="save-schedule"]').dispatchEvent(new w.MouseEvent("click", { bubbles: true, composed: true }));
await wait(100);
const saved = calls.find((c) => c.type === "homepower/schedule/save");
console.log("saved call:", !!saved, "| alerts:", JSON.stringify(alerts));
const ok = !!saved && alerts.length === 1 && alerts[0].startsWith("Saved, but note:") && alerts[0].includes("minimum charge") && !el._modal;
console.log(ok ? "ok   warning shown after save, modal closed" : "FAIL warning path");
process.exit(ok ? 0 : 1);
